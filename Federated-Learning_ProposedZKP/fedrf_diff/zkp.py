"""Proposed Zero-Knowledge Proof (ZKP)-based client authentication.

The same protocol, group and code as FedRF-Diff v12
(Fed_Code_v12_ProposedPedersenZKP_LaplaceDP_eps2-3/fedrf_diff/zkp.py); here it
authenticates every hospital client before the server accepts its uploaded
forest (Step 2-3 of the tree-level federation). Only lambda is a parameter
(config.py "zkp_lambda") instead of a module constant.

Implements the "Proposed Zero-Knowledge Proof (ZKP)-Based Authentication"
protocol once per client and round. The ZKP is used only for client
authentication: it works on scalars (the client's secret v_t, blinding factors
and responses), not on the transmitted update. A client that fails
authentication has its update rejected for that round; the proof changes no
learned value. The forest itself is checked by the server's structural
validation (server.check_update), not by the ZKP.

  Public parameters known to both: prime q, generators g and h.
  Client holds secret v_t (committed across rounds).
  Round 1: previous commitment C_{t-1} initialised to 1.

  1. client -> server  Pedersen commitment  C_t = g^{v_t} h^{r_t} (C_{t-1})^lambda
  2. client -> server  chooses two random integers k, tau (fresh every session)
                       and sends T = g^k h^tau
  3. server -> client  random challenge c (fresh every time)
  4. client -> server  responses  r_v = k + c v_t (mod q),  r_s = tau + c r_t (mod q)
     server            verifies  g^{r_v} h^{r_s} =? T (C_base)^c,
                       where C_base = C_t / (C_{t-1})^lambda
     Decision - do both sides match?
  5. values match        -> "Authentication Successful" (update accepted)
  6. values do not match -> "Authentication Failed" (update rejected)

Implementation choices the diagram leaves open:

* Group: the diagram's "prime q" is realised as a 2048-bit prime p = k q + 1
  with a 256-bit prime q: group elements (C_t, T, g, h) are reduced mod p,
  scalars (v_t, r_t, k, tau, c, r_v, r_s, lambda) mod q, the order of the
  subgroup generated by g and h. p, q, g and h are derived from the public
  string SEED with SHA-256 ("nothing up my sleeve"), so nobody knows
  log_g(h) and anyone can regenerate them (generate_group, setup).
* Secret: at enrolment each client draws a long-term secret key (a random
  scalar that never leaves the client); its round secret is the scalar
  v_t = SHA-256(key || client || t) mod q.
* Chain: C_{t-1} is the client's last *successfully authenticated*
  commitment. Client and server both keep it; after "Authentication
  Successful" both move on to C_t, after "Authentication Failed" both keep
  C_{t-1}. lambda = LAMBDA (a public scalar).
* Challenge c is drawn by the server uniformly from Z_q in every session
  (interactive, not Fiat-Shamir), so replaying an old session's messages fails.

Timing per client and round: proof generation = client steps 1, 2 and 4;
proof verification = server step 3 plus the check and the decision;
authentication = the whole session (steps 1-6).

All ZKP settings live below; there is no command-line option for them.
"""

from __future__ import annotations

import functools
import hashlib
import secrets
import time
from dataclasses import dataclass, field

try:  # gmpy2 makes 2048-bit modular arithmetic several times faster.
    import gmpy2

    _mpz = gmpy2.mpz
    _powmod = gmpy2.powmod
    _next_prime = gmpy2.next_prime

    def _is_prime(n: int) -> bool:
        return bool(gmpy2.is_prime(n, 50))
except ImportError:  # pragma: no cover - exercised only without gmpy2
    _mpz = int
    _powmod = pow

    def _is_prime(n: int) -> bool:  # Miller-Rabin with 50 random bases
        if n < 4:
            return n in (2, 3)
        d, s = n - 1, 0
        while d % 2 == 0:
            d, s = d // 2, s + 1
        for _ in range(50):
            x = pow(secrets.randbelow(n - 3) + 2, d, n)
            if x in (1, n - 1):
                continue
            for _ in range(s - 1):
                x = x * x % n
                if x == n - 1:
                    break
            else:
                return False
        return True

    def _next_prime(n: int) -> int:
        n += 1
        while not _is_prime(n):
            n += 1
        return n


# (p bits, q bits) of each group; the primes are derived from SEED.
GROUPS = {"pedersen2048": (2048, 256), "test512": (512, 256)}

# --- ZKP settings ----------------------------------------------------------
ENABLED = True  # authenticate every client every round
GROUP = "pedersen2048"  # 2048-bit p, 256-bit q (secure); "test512" is fast but NOT secure
LAMBDA = 2  # lambda: weight of the previous commitment in C_t = g^v h^r (C_{t-1})^lambda
PROTOCOL = "FedRF-Diff Proposed Pedersen ZKP"  # domain separator of v_t
SEED = "FedRF-Diff Pedersen ZKP group"  # public seed of p, q, g, h


def settings() -> dict:
    p_bits, q_bits = GROUPS[GROUP]
    return {"enabled": ENABLED, "protocol": "proposed pedersen zkp authentication (chained commitment)",
            "group": GROUP, "p_bits": p_bits, "q_bits": q_bits, "lambda": LAMBDA,
            "challenge": "interactive, uniform in Z_q", "seed": SEED}


# --- group ----------------------------------------------------------------
def _expand(label: str, bits: int) -> int:
    """``bits`` pseudo-random bits from SHA-256(SEED | label | counter)."""
    out, counter = b"", 0
    while len(out) * 8 < bits:
        out += hashlib.sha256(f"{SEED}|{label}|{counter}".encode()).digest()
        counter += 1
    return int.from_bytes(out, "big") >> (len(out) * 8 - bits)


def generate_group(p_bits: int, q_bits: int) -> tuple[int, int]:
    """Primes (p, q) with q | p - 1, p of p_bits and q of q_bits bits, from SEED."""
    q = int(_next_prime(_expand(f"q{q_bits}", q_bits) | (1 << (q_bits - 1))))
    if q.bit_length() != q_bits:
        raise ValueError("q overflowed its bit length; change SEED")
    k = ((1 << (p_bits - 1)) + _expand(f"k{p_bits}", p_bits - 2)) // q + 1
    k += k % 2  # k even, so p = k q + 1 is odd
    while True:
        p = k * q + 1
        if p.bit_length() != p_bits:
            raise ValueError("no prime found in range; change SEED")
        if _is_prime(p):
            return p, q
        k += 2


def _subgroup_element(p: int, q: int, label: str) -> int:
    """Hash to the order-q subgroup: x^((p-1)/q) mod p for x = H(SEED | label)."""
    counter = 0
    while True:
        x = _expand(f"{label}{counter}", p.bit_length() + 64) % p
        y = int(_powmod(_mpz(x), _mpz((p - 1) // q), _mpz(p)))
        if y > 1:
            return y
        counter += 1


class FixedBase:
    """Fast powers of a fixed base: precomputed base^(d * 256^j) for every byte d."""

    WINDOW = 8

    def __init__(self, base: int, p: int, bits: int):
        self.p = _mpz(p)
        self.tables = []
        b = _mpz(base)
        for _ in range((bits + self.WINDOW - 1) // self.WINDOW):
            row = [_mpz(1)]
            for _ in range((1 << self.WINDOW) - 1):
                row.append(row[-1] * b % self.p)
            self.tables.append(row)
            b = row[-1] * b % self.p  # base^(256^(j+1))

    def pow(self, e: int) -> int:
        acc, e = _mpz(1), int(e)
        for row in self.tables:
            d = e & 0xFF
            if d:
                acc = acc * row[d] % self.p
            e >>= self.WINDOW
            if not e:
                break
        return acc


@dataclass(frozen=True)
class PublicParams:
    p: int  # group modulus, p = k q + 1
    q: int  # prime order of the subgroup generated by g and h (scalars live mod q)
    g: int
    h: int  # second generator, log_g(h) unknown
    group: str = ""
    g_fixed: FixedBase | None = field(default=None, repr=False, compare=False)
    h_fixed: FixedBase | None = field(default=None, repr=False, compare=False)

    @property
    def p_bytes(self) -> int:
        return (int(self.p).bit_length() + 7) // 8

    @property
    def q_bytes(self) -> int:
        return (int(self.q).bit_length() + 7) // 8

    def g_pow(self, e: int) -> int:
        return self.g_fixed.pow(e % self.q)

    def h_pow(self, e: int) -> int:
        return self.h_fixed.pow(e % self.q)

    def commit(self, v: int, r: int) -> int:
        """Pedersen commitment g^v h^r."""
        return self.g_pow(v) * self.h_pow(r) % self.p

    def in_subgroup(self, x: int) -> bool:
        return 0 < x < self.p and _powmod(_mpz(x), self.q, self.p) == 1


@functools.lru_cache(maxsize=None)
def _setup(group: str) -> PublicParams:
    p, q = generate_group(*GROUPS[group])
    g, h = _subgroup_element(p, q, "g"), _subgroup_element(p, q, "h")
    bits = q.bit_length()
    return PublicParams(p=_mpz(p), q=_mpz(q), g=_mpz(g), h=_mpz(h), group=group,
                        g_fixed=FixedBase(g, p, bits), h_fixed=FixedBase(h, p, bits))


def setup(group: str | None = None) -> PublicParams:
    """Public parameters (q, g, h and the modulus p); the group defaults to GROUP."""
    group = GROUP if group is None else group
    if group not in GROUPS:
        raise ValueError(f"unknown ZKP group {group!r}; choose from {sorted(GROUPS)}")
    return _setup(group)


def _rand(pp: PublicParams) -> int:
    return _mpz(secrets.randbelow(int(pp.q)))


# --- the two parties -----------------------------------------------------------
class ClientProver:
    """Client side: holds the secret and the last authenticated commitment C_{t-1}."""

    def __init__(self, pp: PublicParams, client_id: str, lam: int = LAMBDA):
        self.pp = pp
        self.client_id = client_id
        self.lam = lam  # public weight of C_{t-1}
        self._key = secrets.token_bytes(32)  # long-term secret, never sent
        self.C_prev = _mpz(1)  # round 1: C_{t-1} = 1
        self._v = self._r = self._k = self._tau = None
        self.C_t = None
        self.last_transcript: tuple | None = None  # (C_t, T, r_v, r_s) of the last session

    def secret(self, round_: int) -> int:
        """v_t = SHA-256(key || client || t) mod q (a scalar)."""
        data = self._key + f"|{PROTOCOL}|{self.client_id}|{round_}".encode()
        return _mpz(int.from_bytes(hashlib.sha256(data).digest(), "big") % int(self.pp.q))

    def commit(self, round_: int) -> int:
        """Step 1: C_t = g^{v_t} h^{r_t} (C_{t-1})^lambda."""
        pp = self.pp
        self._v, self._r = self.secret(round_), _rand(pp)
        self.C_t = pp.commit(self._v, self._r) * _powmod(self.C_prev, self.lam, pp.p) % pp.p
        return self.C_t

    def announce(self) -> int:
        """Step 2: fresh random k, tau; T = g^k h^tau."""
        self._k, self._tau = _rand(self.pp), _rand(self.pp)
        return self.pp.commit(self._k, self._tau)

    def respond(self, c: int) -> tuple[int, int]:
        """Step 4: r_v = k + c v_t (mod q), r_s = tau + c r_t (mod q)."""
        q = self.pp.q
        return (self._k + c * self._v) % q, (self._tau + c * self._r) % q

    def finish(self, authenticated: bool) -> None:
        """Steps 5/6: move the chain on only after a successful authentication."""
        if authenticated:
            self.C_prev = self.C_t
        self._v = self._r = self._k = self._tau = None


class ServerVerifier:
    """Server side: the last authenticated commitment C_{t-1} of every client."""

    def __init__(self, pp: PublicParams, lam: int = LAMBDA):
        self.pp = pp
        self.lam = lam  # public weight of C_{t-1}, the same as the clients'
        self.C_prev: dict[str, int] = {}

    def challenge(self) -> int:
        """Step 3: random challenge c, fresh every time."""
        return _rand(self.pp)

    def verify(self, client_id: str, C_t: int, T: int, c: int, r_v: int, r_s: int) -> bool:
        """g^{r_v} h^{r_s} =? T (C_base)^c with C_base = C_t / (C_{t-1})^lambda."""
        pp = self.pp
        if not (pp.in_subgroup(C_t) and pp.in_subgroup(T) and 0 <= r_v < pp.q and 0 <= r_s < pp.q):
            return False
        C_prev = self.C_prev.get(client_id, _mpz(1))
        C_base = C_t * pow(int(_powmod(C_prev, self.lam, pp.p)), -1, int(pp.p)) % pp.p
        return pp.commit(r_v, r_s) == T * _powmod(C_base, c, pp.p) % pp.p

    def decide(self, client_id: str, C_t: int, ok: bool) -> None:
        """Steps 5/6: remember C_t only after a successful authentication."""
        if ok:
            self.C_prev[client_id] = C_t


# --- one session -------------------------------------------------------------
@dataclass
class Session:
    """Outcome, timing (seconds) and message sizes (bytes) of one client's authentication."""

    authenticated: bool
    vectors: int  # leaf vectors in the forest this authentication admits
    proof_generation_s: float  # client steps 1, 2, 4
    proof_verification_s: float  # server step 3, check and decision
    authentication_s: float  # whole session
    bytes_up: int  # client -> server: C_t, T, r_v, r_s
    bytes_down: int  # server -> client: c and the outcome

    @property
    def outcome(self) -> str:
        return "Valid" if self.authenticated else "Invalid"


def authenticate(pp: PublicParams, prover: ClientProver, verifier: ServerVerifier, round_: int,
                 vectors: int = 0, replay: tuple | None = None) -> Session:
    """One authentication session (steps 1-6) between a client and the server.

    ``replay`` = (C_t, T, r_v, r_s) of an earlier session: an impostor who
    replays them instead of the client (tests and
    ``pipeline.run_federation(impersonate=...)``); the fresh challenge makes it fail.
    """
    cid = prover.client_id
    t0 = time.perf_counter()
    gen = ver = 0.0
    if replay is None:
        C_t = prover.commit(round_)  # 1. Pedersen commitment
        T = prover.announce()  # 2. T = g^k h^tau
    else:
        C_t, T = replay[0], replay[1]
    t1 = time.perf_counter()
    gen += t1 - t0
    c = verifier.challenge()  # 3. random challenge
    t2 = time.perf_counter()
    ver += t2 - t1
    r_v, r_s = prover.respond(c) if replay is None else replay[2:]  # 4. responses
    t3 = time.perf_counter()
    gen += t3 - t2
    ok = verifier.verify(cid, C_t, T, c, r_v, r_s)  # check; decision
    verifier.decide(cid, C_t, ok)  # 5. successful / 6. failed
    t4 = time.perf_counter()
    ver += t4 - t3
    if replay is None:
        prover.finish(ok)
        prover.last_transcript = (C_t, T, r_v, r_s)
    return Session(authenticated=bool(ok), vectors=vectors,
                   proof_generation_s=gen, proof_verification_s=ver, authentication_s=t4 - t0,
                   bytes_up=2 * pp.p_bytes + 2 * pp.q_bytes, bytes_down=pp.q_bytes + 1)
